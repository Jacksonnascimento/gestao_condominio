-- 10. Tabela de Encomendas
CREATE TABLE GC_ENCOMENDA (
    ENC_COD BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CON_COD INT NOT NULL,
    UNI_COD INT NOT NULL,
    PES_COD_REGISTRO INT NOT NULL,
    ENC_DESTINATARIO VARCHAR(100) NOT NULL,
    ENC_NOME_RECEBIDO_POR VARCHAR(100) NOT NULL,
    ENC_DESCRICAO VARCHAR(255),
    ENC_TIPO VARCHAR(50) NOT NULL,
    ENC_STATUS VARCHAR(20) NOT NULL,
    ENC_DT_RECEBIMENTO TIMESTAMP NOT NULL,
    ENC_OBSERVACOES TEXT,
    ENC_NOME_RETIRADA VARCHAR(100),
    PES_COD_RETIRADA INT,
    ENC_DT_RETIRADA TIMESTAMP,
    ENC_OBS_ATUALIZACAO TEXT,
    ENC_DT_ATUALIZACAO_STATUS TIMESTAMP,

    PRIMARY KEY (ENC_COD),
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO (CON_COD),
    FOREIGN KEY (UNI_COD) REFERENCES GC_UNIDADE (UNI_COD),
    FOREIGN KEY (PES_COD_REGISTRO) REFERENCES GC_PESSOA (PES_COD),
    FOREIGN KEY (PES_COD_RETIRADA) REFERENCES GC_PESSOA (PES_COD),
    CONSTRAINT gc_encomenda_enc_status_check CHECK (enc_status IN ('PENDENTE', 'RETIRADA', 'DEVOLVIDA', 'EXTRAVIADA')),
    CONSTRAINT gc_encomenda_enc_tipo_check CHECK (enc_tipo IN ('CORREIOS', 'TRANSPORTADORA', 'DELIVERY', 'OUTROS'))
);

CREATE INDEX IF NOT EXISTS idx_encomenda_status_dt ON gc_encomenda (enc_status, enc_dt_recebimento DESC);
CREATE INDEX IF NOT EXISTS idx_encomenda_unidade ON gc_encomenda (uni_cod);
CREATE INDEX IF NOT EXISTS idx_encomenda_destinatario ON gc_encomenda (LOWER(enc_destinatario));

-- ===== Banco/5. CREATE TABLE GC_VISITANTE.sql =====

CREATE TABLE GC_VISITANTE (
    VIS_COD INT GENERATED BY DEFAULT AS IDENTITY,
    CON_COD INT NOT NULL,
    UNI_COD INT NOT NULL,
    PES_COD_MORADOR INT, -- Morador que autorizou 
    PES_COD_REGISTRO INT NOT NULL, -- Porteiro/Admin que registrou a entrada
    VIS_NOME VARCHAR(100) NOT NULL,
    VIS_CPF VARCHAR(14), -- Conforme RF, numérico
    VIS_RG VARCHAR(20),  -- Conforme RF, numérico
    VIS_TELEFONE VARCHAR(20),
    VIS_STATUS VARCHAR(20) NOT NULL DEFAULT 'NO_LOCAL',
    VIS_DT_ENTRADA TIMESTAMP NOT NULL DEFAULT NOW(),
    VIS_DT_SAIDA TIMESTAMP,
    VIS_OBSERVACOES TEXT,
    VIS_DT_CADASTRO TIMESTAMP NOT NULL DEFAULT NOW(),
    VIS_DT_ATUALIZACAO TIMESTAMP,

    PRIMARY KEY (VIS_COD),
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO (CON_COD),
    FOREIGN KEY (UNI_COD) REFERENCES GC_UNIDADE (UNI_COD),
    FOREIGN KEY (PES_COD_MORADOR) REFERENCES GC_PESSOA (PES_COD),
    FOREIGN KEY (PES_COD_REGISTRO) REFERENCES GC_PESSOA (PES_COD),
    CONSTRAINT gc_visitante_vis_status_check CHECK (vis_status IN ('NO_LOCAL', 'SAIU'))
);

CREATE INDEX IF NOT EXISTS idx_visitante_status_dt ON gc_visitante (vis_status, vis_dt_entrada DESC);
CREATE INDEX IF NOT EXISTS idx_visitante_unidade ON gc_visitante (uni_cod);
CREATE INDEX IF NOT EXISTS idx_visitante_nome ON gc_visitante (LOWER(vis_nome));

-- ===== Banco/6. GC_AREA_COMUM.sql =====
CREATE TABLE GC_AREA_COMUM (
    ARE_COD SERIAL PRIMARY KEY,
    CON_COD INTEGER NOT NULL REFERENCES GC_CONDOMINIO(CON_COD),
    ARE_NOME VARCHAR(100) NOT NULL,
    ARE_DESCRICAO TEXT,
    ARE_TERMOS_USO TEXT,
    ARE_CAPACIDADE_MAXIMA INTEGER,
    ARE_PERMITE_CONVIDADOS BOOLEAN DEFAULT FALSE,
    ARE_LIMITE_CONVIDADOS INTEGER,
    ARE_DIAS_ANTECEDENCIA_MIN INTEGER DEFAULT 1,
    ARE_DIAS_ANTECEDENCIA_MAX INTEGER DEFAULT 30,
    ARE_ATIVA BOOLEAN DEFAULT TRUE,
    ARE_TAXA_VALOR NUMERIC(10,2),
    ARE_DT_CADASTRO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ARE_DT_ATUALIZACAO TIMESTAMP
);

CREATE TABLE GC_AREA_COMUM_TURNO (
    TUR_COD SERIAL PRIMARY KEY,
    ARE_COD INTEGER NOT NULL REFERENCES GC_AREA_COMUM(ARE_COD) ON DELETE CASCADE,
    TUR_NOME VARCHAR(50) NOT NULL,
    TUR_HORA_INICIO TIME NOT NULL,
    TUR_HORA_FIM TIME NOT NULL,
    TUR_ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE GC_RESERVA (
    RES_COD SERIAL PRIMARY KEY,
    ARE_COD INTEGER NOT NULL REFERENCES GC_AREA_COMUM(ARE_COD),
    TUR_COD INTEGER REFERENCES GC_AREA_COMUM_TURNO(TUR_COD),
    UNI_COD INTEGER NOT NULL REFERENCES GC_UNIDADE(UNI_COD),
    PES_COD_MORADOR INTEGER NOT NULL REFERENCES GC_PESSOA(PES_COD),
    PES_COD_APROVADOR INTEGER REFERENCES GC_PESSOA(PES_COD),
    RES_DATA DATE NOT NULL,
    RES_STATUS VARCHAR(30) NOT NULL,
    RES_TERMOS_ACEITOS BOOLEAN NOT NULL DEFAULT FALSE,
    RES_MOTIVO_REJEICAO TEXT,
    RES_DT_REGISTRO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RES_DT_ATUALIZACAO TIMESTAMP
);

CREATE TABLE GC_RESERVA_CONVIDADO (
    RCV_COD SERIAL PRIMARY KEY,
    RES_COD INTEGER NOT NULL REFERENCES GC_RESERVA(RES_COD) ON DELETE CASCADE,
    RCV_NOME VARCHAR(150) NOT NULL,
    RCV_DOCUMENTO VARCHAR(50)
);
