-- ===== Banco/1. Banco de dados PostgreSQL.sql =====
-- 1. Tabela Principal de Usuários
CREATE TABLE GC_PESSOA (
    PES_COD INT GENERATED BY DEFAULT AS IDENTITY,
    PES_NOME VARCHAR(100) NOT NULL,
    PES_CPF_CNPJ VARCHAR(14) UNIQUE NOT NULL,
    PES_TIPO CHAR(1) DEFAULT('F'),
    PES_EMAIL VARCHAR(100) UNIQUE NOT NULL,
    PES_TELEFONE VARCHAR (20),
    PES_TELEFONE2 VARCHAR (20),
    PES_ATIVO BOOLEAN DEFAULT true,
    PES_DT_CADASTRO TIMESTAMP DEFAULT NOW(),
    PES_DT_ATUALIZACAO TIMESTAMP,
    PES_SENHA_LOGIN VARCHAR(255) NULL,
    PES_IS_GLOBAL_ADMIN BOOLEAN NOT NULL DEFAULT false,
    PES_IMAGEM BYTEA NULL,
    PRIMARY KEY (PES_COD)
);

-- 2. Tabela de Condomínios
CREATE TABLE GC_CONDOMINIO (
    CON_COD INT GENERATED BY DEFAULT AS IDENTITY,
    CON_NOME VARCHAR(100) NOT NULL,
    CON_LOGRADOURO VARCHAR(100),
    CON_NUMERO VARCHAR(10),
    CON_COMPLEMENTO VARCHAR(50),
    CON_BAIRRO VARCHAR(50),
    CON_CIDADE VARCHAR(50),
    CON_ESTADO VARCHAR(2),
    CON_CEP VARCHAR (8),
    CON_PAIS VARCHAR(50) DEFAULT 'Brasil',
    CON_REFERENCIA VARCHAR(100),
    CON_NUMERO_UNIDADES INT,
    CON_TIPOLOGIA VARCHAR(50),
    CON_DT_VENCIMENTO_TAXA INT,
    CON_DT_CADASTRO TIMESTAMP DEFAULT NOW(),
    CON_DT_ATUALIZACAO TIMESTAMP,
    CON_ATIVO BOOLEAN DEFAULT true,
    PRIMARY KEY (CON_COD)
);

-- 3. Tabela de Unidades
CREATE TABLE GC_UNIDADE (
    UNI_COD INT GENERATED BY DEFAULT AS IDENTITY,
    UNI_STATUS_OCUPACAO VARCHAR(50),
    UNI_NUMERO VARCHAR(10) NOT NULL,
    CON_COD INT NOT NULL,
    UNI_DT_CADASTRO TIMESTAMP DEFAULT NOW() NOT NULL,
    UNI_DT_ATUALIZACAO TIMESTAMP,
    UNI_ATIVA BOOLEAN DEFAULT true,
    UNI_BLOCO VARCHAR(50),
    UNI_ANDAR VARCHAR(50),
    UNI_FRACAO_IDEAL DECIMAL(5, 2),
    UNI_AREA_PRIVADA DECIMAL(10, 2),
    UNI_OBSERVACAO TEXT,
    UNI_TIPO VARCHAR(50),
    PRIMARY KEY (UNI_COD),
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO (CON_COD),
    CONSTRAINT gc_unidade_uni_tipo_check CHECK (uni_tipo IN ('APARTAMENTO', 'COMERCIAL', 'GARAGEM', 'DEPOSITO', 'OUTROS'))
);

-- 4. Tabela de Vínculo de Ocupantes (Pessoa x Unidade)
CREATE TABLE GC_OCUPANTE (
    OCU_COD INT GENERATED BY DEFAULT AS IDENTITY,
    PES_COD INT NOT NULL,
    UNI_COD INT NOT NULL,
    OCU_VINCULO VARCHAR(50) NOT NULL,
    OCU_DT_INICIO_OCUPACAO DATE,
    OCU_DT_FIM_OCUPACAO DATE,
    OCU_PERIODO_USO VARCHAR(100),
    OCU_TIPO_PERIODO VARCHAR(50),
    OCU_DT_CADASTRO TIMESTAMP NOT NULL,
    OCU_DT_ATUALIZACAO TIMESTAMP,
    PRIMARY KEY (OCU_COD),
    FOREIGN KEY (PES_COD) REFERENCES GC_PESSOA (PES_COD),
    FOREIGN KEY (UNI_COD) REFERENCES GC_UNIDADE (UNI_COD),
    UNIQUE (PES_COD, UNI_COD)
);

-- 5. Tabela de Associação de Usuário com Condomínio (Funções/Roles)
CREATE TABLE GC_USUARIO_CONDOMINIO (
    PES_COD INT NOT NULL,
    CON_COD INT NOT NULL,
    USC_PAPEL VARCHAR(50) NOT NULL,
    USC_DT_ASSOCIACAO TIMESTAMP DEFAULT NOW() NOT NULL,
    USC_ATIVO_ASSOCIACAO BOOLEAN DEFAULT true NOT NULL,
    USC_DT_ATUALIZACAO TIMESTAMP,
    PRIMARY KEY (PES_COD, CON_COD, USC_PAPEL),
    FOREIGN KEY (PES_COD) REFERENCES GC_PESSOA (PES_COD),
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO (CON_COD)
);

-- 6. Tabela de Contratos
CREATE TABLE GC_CONTRATO (
    CTR_COD INT GENERATED BY DEFAULT AS IDENTITY,
    CON_COD INT NOT NULL,
    CTR_EMPRESA VARCHAR(100) NOT NULL,
    CTR_SERVICO VARCHAR(255) NOT NULL,
    CTR_VALOR DECIMAL(10, 2) NOT NULL,
    CTR_RESPONSAVEL VARCHAR(100),
    CTR_STATUS VARCHAR(50) NOT NULL,
    CTR_DATA_INICIO DATE NOT NULL,
    CTR_DATA_FIM DATE NOT NULL,
    CTR_OBSERVACOES TEXT,
    CTR_DT_CADASTRO TIMESTAMP DEFAULT NOW(),
    CTR_DT_ATUALIZACAO TIMESTAMP,
    PRIMARY KEY (CTR_COD),
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO (CON_COD)
);


-- INDEXES ESSENCIAIS


CREATE INDEX IF NOT EXISTS idx_pessoa_nome_lower ON gc_pessoa (LOWER(pes_nome));
CREATE INDEX IF NOT EXISTS idx_pessoa_email_lower ON gc_pessoa (LOWER(pes_email));

-- 7. Tabela de Comunicados
CREATE TABLE GC_COMUNICADO (
    COM_COD INT GENERATED BY DEFAULT AS IDENTITY,
    COM_TITULO VARCHAR(255) NOT NULL,
    COM_MENSAGEM TEXT NOT NULL,
    COM_PUBLICO_DESTINO VARCHAR(50) NOT NULL,
    COM_IS_URGENTE BOOLEAN NOT NULL DEFAULT FALSE,
    COM_CAMINHO_ANEXO VARCHAR(555),
    COM_DT_CADASTRO TIMESTAMP NOT NULL DEFAULT NOW(),
    PES_COD_CRIADOR INT NOT NULL, 

    PRIMARY KEY (COM_COD),
    FOREIGN KEY (PES_COD_CRIADOR) REFERENCES GC_PESSOA(PES_COD)
);

-- 8. Tabela de Associação (Comunicado <-> Condomínio)
CREATE TABLE GC_COMUNICADO_CONDOMINIO (
    COM_COD INT NOT NULL,
    CON_COD INT NOT NULL,
    
    PRIMARY KEY (COM_COD, CON_COD),
    FOREIGN KEY (COM_COD) REFERENCES GC_COMUNICADO(COM_COD) ON DELETE CASCADE, -- <-- ALTERAÇÃO APLICADA
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO(CON_COD)
);

-- 9. Tabela de Rastreamento de Leitura
CREATE TABLE GC_COMUNICADO_LEITURA (
    COM_COD INT NOT NULL,
    PES_COD INT NOT NULL,
    CLE_DT_LEITURA TIMESTAMP NOT NULL DEFAULT NOW(),
    
    PRIMARY KEY (COM_COD, PES_COD),
    FOREIGN KEY (COM_COD) REFERENCES GC_COMUNICADO(COM_COD) ON DELETE CASCADE, -- <-- ALTERAÇÃO APLICADA
    FOREIGN KEY (PES_COD) REFERENCES GC_PESSOA(PES_COD)
);

-- ===== Banco/2. CREATE TABLE GC_OCORRENCIA.sql =====

CREATE TABLE GC_OCORRENCIA (
    OCO_COD INT GENERATED BY DEFAULT AS IDENTITY,
    CON_COD INT NOT NULL,         
    UNI_COD INT NOT NULL,           
    PES_COD_REGISTRO INT NOT NULL, 
    OCO_TITULO VARCHAR(150) NOT NULL,
    OCO_DESCRICAO TEXT NOT NULL,
    OCO_TIPO VARCHAR(50) NOT NULL,    
    OCO_STATUS VARCHAR(20) NOT NULL DEFAULT 'ABERTA', 
    OCO_DT_REGISTRO TIMESTAMP NOT NULL DEFAULT NOW(),
    OCO_DT_ATUALIZACAO TIMESTAMP,
    OCO_PARECER_FINAL TEXT,
    PES_COD_FINALIZOU INT,        
    OCO_DT_FINALIZACAO TIMESTAMP,

    PRIMARY KEY (OCO_COD),
    FOREIGN KEY (CON_COD) REFERENCES GC_CONDOMINIO (CON_COD),
    FOREIGN KEY (UNI_COD) REFERENCES GC_UNIDADE (UNI_COD),
    FOREIGN KEY (PES_COD_REGISTRO) REFERENCES GC_PESSOA (PES_COD),
    FOREIGN KEY (PES_COD_FINALIZOU) REFERENCES GC_PESSOA (PES_COD),
    CONSTRAINT gc_ocorrencia_oco_status_check CHECK (oco_status IN ('ABERTA', 'EM_ANALISE', 'RESOLVIDA')),
    CONSTRAINT gc_ocorrencia_oco_tipo_check CHECK (oco_tipo IN ('BARULHO', 'CONFLITO', 'MANUTENCAO', 'RECLAMACAO', 'OUTRO')) 
);
CREATE INDEX IF NOT EXISTS idx_ocorrencia_status ON gc_ocorrencia (oco_status);
CREATE INDEX IF NOT EXISTS idx_ocorrencia_dt_registro ON gc_ocorrencia (oco_dt_registro DESC); 



CREATE TABLE GC_OCORRENCIA_COMENTARIO (
    OCC_COD INT GENERATED BY DEFAULT AS IDENTITY,
    OCO_COD INT NOT NULL,
    PES_COD_COMENTARIO INT NOT NULL,
    OCC_COMENTARIO TEXT NOT NULL,
    OCC_DT_COMENTARIO TIMESTAMP NOT NULL DEFAULT NOW(),

    PRIMARY KEY (OCC_COD),
    FOREIGN KEY (OCO_COD) REFERENCES GC_OCORRENCIA (OCO_COD) ON DELETE CASCADE,
    FOREIGN KEY (PES_COD_COMENTARIO) REFERENCES GC_PESSOA (PES_COD)
);
CREATE INDEX IF NOT EXISTS idx_ocorrencia_comentario_dt ON gc_ocorrencia_comentario (occ_dt_comentario DESC); 



CREATE TABLE GC_OCORRENCIA_ANEXO (
    OCA_COD INT GENERATED BY DEFAULT AS IDENTITY,
    OCO_COD INT NOT NULL,
    PES_COD_ANEXO INT NOT NULL,
    OCA_CAMINHO_ARQUIVO VARCHAR(555) NOT NULL, 
    OCA_NOME_ORIGINAL VARCHAR(255),            
    OCA_TIPO_ARQUIVO VARCHAR(100),            
    OCA_TAMANHO_ARQUIVO BIGINT,               
    OCA_DT_ANEXO TIMESTAMP NOT NULL DEFAULT NOW(),

    PRIMARY KEY (OCA_COD),
    FOREIGN KEY (OCO_COD) REFERENCES GC_OCORRENCIA (OCO_COD) ON DELETE CASCADE,
    FOREIGN KEY (PES_COD_ANEXO) REFERENCES GC_PESSOA (PES_COD)
);
CREATE INDEX IF NOT EXISTS idx_ocorrencia_anexo_dt ON gc_ocorrencia_anexo (oca_dt_anexo DESC);

